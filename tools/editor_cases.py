"""Keyboard regression cases ported from the CCP/M editor checks."""

def check_recall(type_command, key, current, shortcut):
    # No saved line yet.  Comment commands avoid launching a program.
    key('ctrl-w')
    current('')
    type_command(';recallone\n')
    current('')
    key('ctrl-w')
    current(';recallone')
    key('ctrl-w')
    current(';recallone')
    type_command('x')
    key('ctrl-w')
    current(';recallonex')
    key('backspace')
    type_command('y\n')
    current('')

    # A new accepted line replaces the only saved line.  Blank submission
    # and abandoning an edit with ^U retain it.
    type_command('\n')
    key('ctrl-w')
    current(';recalloney')
    key('ctrl-u')
    key('ctrl-w')
    current(';recalloney')
    key('ctrl-x')
    type_command('\n')
    current('')

    shortcut('ctrl-alt-2', 1)
    key('ctrl-w')
    current('')
    type_command(';otherconsole\n')
    current('')
    key('ctrl-w')
    current(';otherconsole')
    key('ctrl-x')
    shortcut('ctrl-alt-1', 0)
    key('ctrl-w')
    current(';recalloney')
    key('ctrl-x')
    type_command('\n')
    current('')
    # TMP's 128-byte limit auto-accepts typed input.  Recall of a full
    # buffer must instead wait for Return and reject additional bytes.
    full = ';' + 'a' * 127
    type_command(full)
    current('')
    key('ctrl-w')
    current(full)
    type_command('z')
    current(full)
    key('backspace')
    key('backspace')
    type_command('x')
    current(full[:-2] + 'x')
    type_command('\n')
    current('')
    key('ctrl-w')
    current(full[:-2] + 'x')
    key('ctrl-x')
    type_command('\n')
    current('')


def check_editor(type_command, key, current, shortcut):
    type_command(';abcd')
    key('ctrl-a')
    key('ctrl-a')
    type_command('x')
    current(';abxcd')
    key('ctrl-f')
    key('ctrl-g')
    current(';abxc')
    key('ctrl-b')
    key('ctrl-f')
    type_command('z')
    current(';zabxc')
    key('ctrl-b')
    key('ctrl-b')
    type_command('e\n')
    current('')
    key('up')
    current(';zabxce')
    key('home')
    key('up')                   # Up is exactly ^W: nonempty means End.
    type_command('f')
    current(';zabxcef')
    key('home')
    key('right')
    type_command('q')
    current(';qzabxcef')
    key('end')
    key('left')
    key('delete')
    current(';qzabxce')
    key('backspace')
    current(';qzabxc')
    key('home')
    key('right')
    key('ctrl-k')
    type_command('fresh')
    current(';fresh')
    key('home')
    key('ctrl-x')               # Nothing to delete to the left of Home.
    current(';fresh')
    for _ in range(3):
        key('right')
    key('ctrl-x')
    # Prefix removal must retain the suffix in the actual returned buffer.
    key('home')
    type_command(';')
    current(';esh')
    key('end')
    key('ctrl-x')
    type_command('\n')
    current('')

    type_command(';a\tbc')
    key('home')
    key('right')
    key('right')
    type_command('z')
    current(';az\tbc')
    key('right')               # Cross the tab as one buffer character.
    key('backspace')
    current(';azbc')
    key('end')
    key('ctrl-x')
    type_command('\n')
    current('')

    # Retyping and physical newlines must preserve the logical cursor.
    type_command(';abc')
    key('left')
    key('ctrl-r')
    type_command('x\n')
    current('')
    key('up')
    current(';abxc')
    key('left')
    key('ctrl-e')
    type_command('y\n')
    current('')
    key('up')
    current(';abxyc')
    key('end')
    key('ctrl-x')
    type_command('\n')
    current('')

    type_command(';a')
    key('ctrl-d')               # Literal ^D displays in two screen cells.
    type_command('b')
    key('home')
    for _ in range(3):
        key('right')
    key('left')
    key('delete')
    current(';ab')
    key('end')
    key('ctrl-x')
    type_command('\n')
    current('')

    wrapped = ';' + 'a' * 77 + 'bcd'
    type_command(wrapped)
    key('home')
    key('end')
    for _ in range(3):
        key('left')
    type_command('x')
    current(wrapped[:-3] + 'xbcd')
    # The cursor remains inside the line across a console switch.
    shortcut('ctrl-alt-2', 1)
    type_command(';side')
    key('home')
    key('end')
    key('ctrl-x')
    type_command('\n')
    shortcut('ctrl-alt-1', 0)
    type_command('y')
    current(wrapped[:-3] + 'xybcd')
    type_command('\n')          # Return from the middle accepts the suffix.
    current('')
    key('up')
    current(wrapped[:-3] + 'xybcd')
    key('end')
    key('ctrl-x')
    type_command('\n')
    current('')
